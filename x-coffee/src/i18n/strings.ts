const TABLES: Record<Lang, Record<StringKey, string>> = { en, ar };

export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let s = TABLES[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** "5 min" / "5 دقائق" with Arabic number agreement. */
export function minutes(seconds: number, lang: Lang): string {
  const m = Math.max(1, Math.round(seconds / 60));
  if (lang === 'en') return m === 1 ? '1 min' : `${m} min`;
  if (m === 1) return 'دقيقة';
  if (m === 2) return 'دقيقتين';
  if (m <= 10) return `${m} دقائق`;
  return `${m} دقيقة`;
}
